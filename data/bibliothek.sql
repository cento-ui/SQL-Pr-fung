-- Datenbank bibliothek  (LERN-DATEN)
-- Schema: wie RDB_SQL_Arbeitsblatt (entspricht bibliothek.db / Online-DB Leipzig).
-- Daten: Die 6 Buecher, 6 Autoren, 3 Verlage und 7 Zuordnungen aus den Folien sind
-- uebernommen (Ids, Titel, ISBN, Jahr, Verlag). ALLE UEBRIGEN DATEN SIND ERFUNDENE,
-- PLAUSIBLE LERN-DATEN. Die Tipp-Zahlen im Arbeitsblatt (z. B. "14 Datensaetze")
-- gelten fuer die Originaldatenbank und passen NICHT zu diesen Lern-Daten.

CREATE TABLE verlag (
  verlagsid INTEGER PRIMARY KEY,
  name TEXT,
  ort TEXT
);

CREATE TABLE autor (
  autorid INTEGER PRIMARY KEY,
  nachname TEXT,
  zusatz TEXT,
  vornamen TEXT
);

CREATE TABLE buch (
  buchid INTEGER PRIMARY KEY,
  titel TEXT,
  isbn TEXT,
  auflage TEXT,
  jahr INTEGER,
  preis REAL,
  waehrung TEXT,
  signatur TEXT,
  verlagsid INTEGER REFERENCES verlag(verlagsid)
);

CREATE TABLE buch_aut (
  buchid INTEGER REFERENCES buch(buchid),
  autorid INTEGER REFERENCES autor(autorid),
  rolle TEXT,
  rang INTEGER,
  PRIMARY KEY (buchid, autorid)
);

CREATE TABLE schlagwort (
  swid INTEGER PRIMARY KEY,
  schlagwort TEXT
);

CREATE TABLE buch_sw (
  buchid INTEGER REFERENCES buch(buchid),
  swid INTEGER REFERENCES schlagwort(swid),
  PRIMARY KEY (buchid, swid)
);

